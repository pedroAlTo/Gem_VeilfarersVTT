export const MODE_LABEL = { auto: 'La mesa lo aplica', partial: 'La mesa lo aplica cuando puede', reminder: 'La mesa lo recuerda', info: 'Descriptivo' };

// Everything about one tag: its name, the book's rule, the book and what the table does.
export function tagInfo(tag) {
  const canon = canonicalTag(tag), [id, value] = canon.split(':');
  // Area with a band is the Explosive procedure in that band (Rust & Steel 12.06).
  const ruleKey = id === 'area' && value ? 'area-band' : id;
  const rule = RULES[ruleKey] || RULES[id] || null;
  const [mode, table] = TABLE_USE[id] || [I, ''];
  return { id, value: value || '', label: tagLabel(canon), rule: rule?.rule || '', book: rule?.book || (TABLE_USE[id] ? 'Veilfarers VTT' : ''), mode, modeLabel: MODE_LABEL[mode], table };
}
